// Packs every book in content/ into src/generated/packs.ts.
// Workers have no filesystem, so content is compiled into the bundle at build time.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const CONTENT = new URL("../content/", import.meta.url).pathname;
const OUT = new URL("../src/generated/packs.ts", import.meta.url).pathname;

function parseEntry(file, raw) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) throw new Error(`${file}: bad frontmatter line "${line}"`);
    const [, key, value] = kv;
    meta[key] = value.startsWith("[")
      ? value.slice(1, -1).split(",").map((s) => s.trim()).filter(Boolean)
      : /^\d+$/.test(value) ? Number(value) : value;
  }
  const sections = {};
  for (const part of m[2].split(/^## /m).slice(1)) {
    const nl = part.indexOf("\n");
    sections[part.slice(0, nl).trim().toLowerCase()] = part.slice(nl + 1).trim();
  }
  if (typeof meta.number !== "number" || !meta.title || !sections.text) {
    throw new Error(`${file}: needs number, title and a "## Text" section`);
  }
  return {
    number: meta.number,
    title: meta.title,
    themes: meta.themes ?? [],
    text: sections.text,
    reflection: sections.reflection,
    question: sections.question,
    practice: sections.practice,
  };
}

const packs = [];
for (const dir of (await readdir(CONTENT, { withFileTypes: true })).filter((d) => d.isDirectory())) {
  const base = join(CONTENT, dir.name);
  const pack = JSON.parse(await readFile(join(base, "pack.json"), "utf8"));
  if (pack.id !== dir.name) throw new Error(`${dir.name}/pack.json: id must be "${dir.name}"`);
  const files = (await readdir(join(base, "entries"))).filter((f) => f.endsWith(".md")).sort();
  pack.entries = await Promise.all(
    files.map(async (f) => parseEntry(`${dir.name}/${f}`, await readFile(join(base, "entries", f), "utf8")))
  );
  pack.entries.sort((a, b) => a.number - b.number);
  const numbers = new Set(pack.entries.map((e) => e.number));
  if (numbers.size !== pack.entries.length) throw new Error(`${dir.name}: duplicate entry numbers`);
  packs.push(pack);
}

await mkdir(dirname(OUT), { recursive: true });
await writeFile(
  OUT,
  `// Generated by scripts/bundle.mjs. Do not edit; edit content/ instead.\n` +
    `import type { Pack } from "../types.js";\n\n` +
    `export const packs: Pack[] = ${JSON.stringify(packs, null, 1)};\n`
);
console.log(`bundled ${packs.map((p) => `${p.id} (${p.entries.length} entries)`).join(", ")}`);
